export function demoGenerate(req: GenerateRequest): GenerateResponse {
  const step = req.history.length;
  const genreKey = req.genre in OPENINGS ? req.genre : "悬疑推理";
  let scene: string;
  if (step === 0) {
    scene = OPENINGS[genreKey];
  } else {
    const pool = CONTINUATIONS[genreKey] ?? [];
    scene = step - 1 < pool.length ? pool[step - 1] : GENERIC_CONTINUATION;
  }
  const choices = CHOICE_SETS[step % CHOICE_SETS.length];
  return { scene, choices, demo: true };
}
